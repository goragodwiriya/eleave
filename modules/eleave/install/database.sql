-- **ประกาศที่นี่ที่เดียว** ห้ามประกาศซ้ำใน install/database.sql ของโปรเจ็ค
-- และห้ามเขียน CREATE TABLE ซ้ำไว้ในตัวปรับรุ่นอีกชุด
--
-- ข้อกำหนด: InnoDB + utf8mb4 และเขียน PRIMARY KEY/KEY ไว้ในคำสั่ง CREATE TABLE
-- เลย — ของเดิมประกาศ CHARSET=utf8 (คือ utf8mb3) และแยกคีย์ไปเป็น ALTER TABLE
-- ท้ายไฟล์แบบที่ phpMyAdmin ส่งออกมา ทำให้ติดตั้งใหม่ได้ตาราง utf8mb3
-- และตารางที่ ensureTable สร้างตอนปรับรุ่นไม่ได้ดัชนีติดมาด้วย
-- ---------------------------------------------------------------------------

CREATE TABLE `{prefix}_leave` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `topic` varchar(150) NOT NULL,
  `detail` text NOT NULL,
  `num_days` tinyint(4) NOT NULL,
  `is_active` tinyint(1) NOT NULL DEFAULT 1,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE `{prefix}_leave_items` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `member_id` int(11) NOT NULL,
  `leave_id` int(11) NOT NULL,
  `status` tinyint(1) NOT NULL,
  `approve` tinyint(1) DEFAULT NULL,
  `closed` tinyint(1) DEFAULT NULL,
  `department` varchar(10) DEFAULT NULL,
  `detail` text NOT NULL,
  `communication` text NOT NULL,
  `start_date` date NOT NULL,
  `start_period` tinyint(1) NOT NULL,
  `end_date` date NOT NULL,
  `end_period` tinyint(1) NOT NULL,
  `created_at` datetime NOT NULL,
  `days` float NOT NULL DEFAULT 0,
  `reason` varchar(255) DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `member_id` (`member_id`),
  KEY `closed` (`closed`),
  KEY `status` (`status`),
  KEY `start_date` (`start_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

